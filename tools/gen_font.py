#!/usr/bin/env python3
"""Bakes m5x7 (Daniel Linssen, CC0) into src/game/font_data.odin as bit rows.
Usage: tools/gen_font.py   (needs Pillow). Glyphs ASCII 32..126, 8 wide, 10 rows, baseline at row 8."""
import os
from PIL import Image, ImageDraw, ImageFont

here = os.path.dirname(os.path.abspath(__file__))
font = ImageFont.truetype(os.path.join(here, "..", "assets", "m5x7.ttf"), 16)
ROWS, TOP = 10, 8  # rows per glyph, baseline row
out = ["// Generated by tools/gen_font.py from m5x7 by Daniel Linssen (managore), CC0. Do not edit.", "package game", "",
       "FONT_ROWS :: 10", ""]
rows, adv = [], []
for code in range(32, 127):
    ch = chr(code)
    im = Image.new("L", (16, 16), 0)
    ImageDraw.Draw(im).text((0, TOP), ch, font=font, fill=255, anchor="ls")
    px = im.load()
    glyph = []
    # rows run from baseline-TOP to baseline-TOP+ROWS; the baseline is drawn at y=TOP in the 16x16 image
    for y in range(0, ROWS):
        bits = 0
        for x in range(8):
            if px[x, y] > 127:
                bits |= 1 << (7 - x)
        glyph.append(bits)
    rows.append(glyph)
    a = int(round(font.getlength(ch)))
    adv.append(max(a, 1) if ch != " " else 3)
out.append("FONT_GLYPHS := [95][FONT_ROWS]u8{")
for code, g in zip(range(32, 127), rows):
    out.append("\t{" + ", ".join("0x%02x" % b for b in g) + "}, // %r" % chr(code))
out.append("}")
out.append("")
out.append("FONT_ADVANCE := [95]u8{" + ", ".join(str(a) for a in adv) + "}")
open(os.path.join(here, "..", "src", "game", "font_data.odin"), "w").write("\n".join(out) + "\n")
print("wrote font_data.odin; widths", min(adv), max(adv))
